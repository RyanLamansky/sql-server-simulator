// The SQL sort orders over code pages 850 and 437: what CHECKSUM folds for
// their varchar data.
internal static partial class ChecksumWeights
{
    /// <summary>
    /// Folds <paramref name="text"/>, <c>varchar</c> data under one of the
    /// SQL collations over code pages 850 and 437, as <c>CHECKSUM</c> does:
    /// each byte's weight under the name's sort order folds as
    /// <c>h = rotl(h, 4) ^ weight</c> from zero, <c>æ</c>, <c>Æ</c> and
    /// <c>ß</c> taking two places (<c>rotl(h, 8)</c>) where the sort order
    /// expands them, and a binary name's bytes folding as signed bytes — read
    /// off <c>CHECKSUM</c> of every byte alone and beside another under all
    /// twenty names, and checked over random strings (probed 2026-10-17
    /// against SQL Server 2025); false for any other collation.
    /// </summary>
    internal static bool TryFoldSqlSortOrder(Collation collation, string text, out uint hash)
    {
        hash = 0;
        if (!Collation.SqlServerSortOrders.TryGetValue(collation.Name, out var order))
            return false;
        // A binary name's bytes fold as signed bytes.
        if (order.OrderNumber is 30 or 40)
        {
            foreach (var b in collation.StorageEncoding.GetBytes(text))
                hash = BitOperations.RotateLeft(hash, 4) ^ (uint)(sbyte)b;
            return true;
        }
        ReadOnlySpan<ushort> weights;
        var expands = ExpansionLigaturesAndSharpS;
        switch (order.OrderNumber)
        {
            case 31:
                weights = SortOrder31;
                expands = ExpansionLigatures;
                break;
            case 32:
            case 33:
                weights = SortOrder32;
                expands = ExpansionLigatures;
                break;
            case 34:
                weights = SortOrder34;
                expands = ExpansionLigatures;
                break;
            case 41:
                weights = SortOrder41;
                break;
            case 42:
            case 43:
                weights = SortOrder42;
                break;
            case 44:
                weights = SortOrder44;
                break;
            case 49:
                weights = SortOrder49;
                expands = ExpansionNone;
                break;
            case 55:
                weights = SortOrder55;
                break;
            case 56:
                weights = SortOrder56;
                break;
            case 57:
                weights = SortOrder57;
                break;
            case 58:
                weights = SortOrder58;
                expands = ExpansionSharpS;
                break;
            case 59:
                weights = SortOrder59;
                expands = ExpansionSharpS;
                break;
            case 60:
                weights = SortOrder58;
                expands = ExpansionSharpS;
                break;
            case 61:
                weights = SortOrder56;
                break;
            default:
                return false;
        }
        foreach (var b in collation.StorageEncoding.GetBytes(text))
            hash = BitOperations.RotateLeft(hash, Expands(expands, b) ? 8 : 4) ^ weights[b];
        return true;
    }

    // Which of the three expanding bytes (code page 850's and 437's 0x91 æ,
    // 0x92 Æ and 0xE1 ß) take two places under a sort order.
    private const int ExpansionNone = 0;
    private const int ExpansionSharpS = 1;
    private const int ExpansionLigatures = 2;
    private const int ExpansionLigaturesAndSharpS = 3;

    private static bool Expands(int expansion, byte b) => b switch
    {
        0x91 or 0x92 => (expansion & ExpansionLigatures) != 0,
        0xE1 => (expansion & ExpansionSharpS) != 0,
        _ => false,
    };

