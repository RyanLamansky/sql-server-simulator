/// <summary>
/// The case mapping <c>UPPER</c> / <c>LOWER</c> apply under a collation.
/// Real carries three tables of its own, chosen by the collation's version,
/// none of them the modern Unicode mapping .NET's <c>TextInfo</c> applies:
/// one shared by every unversioned, <c>_90</c> and <c>SQL_</c> collation, one
/// by the <c>_100</c> collations and one by the <c>_140</c> collations, the
/// same under every suffix (<c>_BIN</c> / <c>_BIN2</c> / <c>_CS</c> /
/// <c>_SC</c> / <c>_UTF8</c> …). A Turkish collation of any version (the
/// <c>SQL_…_CP1254</c> pair too) and an Azeri <c>_100</c> one map the dotted
/// and dotless I in the Turkish way — <c>UPPER('i')</c> is <c>İ</c> and
/// <c>LOWER('I')</c> <c>ı</c> — and nothing else differently; Lithuanian's
/// special casing isn't applied. A supplementary character never maps, under
/// an <c>_SC</c> collation included. All of it read off every BMP character
/// (probed 2026-09-28 against SQL Server 2025).
/// </summary>
/// <remarks>
/// Each table is a list of runs — a first character, a count, the stride
/// between the characters and the delta to add — expanded once into a
/// 64K lookup when a collation of that version first needs it.
/// </remarks>
internal sealed class CaseMap
{
    private static readonly CaseMap?[] Shared = new CaseMap?[6];

    private readonly char[] upper;
    private readonly char[] lower;

    private CaseMap(char[] upper, char[] lower)
    {
        this.upper = upper;
        this.lower = lower;
    }

    /// <summary>
    /// The mapping <paramref name="collation"/> applies: its version's table,
    /// with the Turkish I pair where the collation takes it.
    /// </summary>
    public static CaseMap For(Collation collation)
    {
        var name = collation.Name;
        var version = Collation.TryGetMetrics(name, out var metrics) ? metrics.Version : 0;
        var table = version switch
        {
            2 => 1,
            >= 3 => 2,
            _ => 0,
        };
        var turkish = name.StartsWith("Turkish_", StringComparison.OrdinalIgnoreCase)
            || name.StartsWith("SQL_Latin1_General_CP1254_", StringComparison.OrdinalIgnoreCase)
            || (table == 1 && name.StartsWith("Azeri_", StringComparison.OrdinalIgnoreCase));
        var slot = (table * 2) + (turkish ? 1 : 0);
        if (Shared[slot] is { } built)
            return built;
        var (upperRuns, lowerRuns) = table switch
        {
            0 => (Upper80, Lower80),
            1 => (Upper100, Lower100),
            _ => (Upper140, Lower140),
        };
        var upper = Expand(upperRuns);
        var lower = Expand(lowerRuns);
        if (turkish)
        {
            upper['i'] = '\u0130';
            lower['I'] = '\u0131';
        }
        var map = new CaseMap(upper, lower);
        return Interlocked.CompareExchange(ref Shared[slot], map, null) ?? map;
    }

    private static char[] Expand(int[] runs)
    {
        var map = new char[65536];
        for (var c = 0; c < map.Length; c++)
            map[c] = (char)c;
        for (var r = 0; r < runs.Length; r += 4)
        {
            for (int k = 0, c = runs[r]; k < runs[r + 1]; k++, c += runs[r + 2])
                map[c] = (char)(c + runs[r + 3]);
        }
        return map;
    }

    /// <summary><paramref name="value"/> uppercased, or the same instance when nothing maps.</summary>
    public string ToUpper(string value) => Map(value, this.upper);

    /// <summary><paramref name="value"/> lowercased, or the same instance when nothing maps.</summary>
    public string ToLower(string value) => Map(value, this.lower);

    private static string Map(string value, char[] map)
    {
        var first = 0;
        while (first < value.Length && map[value[first]] == value[first])
            first++;
        if (first == value.Length)
            return value;
        return string.Create(value.Length, (value, map, first), static (span, state) =>
        {
            state.value.AsSpan(0, state.first).CopyTo(span);
            for (var i = state.first; i < span.Length; i++)
                span[i] = state.map[state.value[i]];
        });
    }

